if(process.env.WORKERS_CI==='1'&&process.env.WORKERS_CI_BRANCH&&process.env.WORKERS_CI_BRANCH!=='main'){
 console.error(`Refusing Cloudflare Worker build from non-production branch: ${process.env.WORKERS_CI_BRANCH}`);
 process.exit(1);
}

import fs from'node:fs';
import path from'node:path';

const root=process.cwd();
const inbox=path.join(root,'public','assets','puck-inbox');
const out=path.join(root,'src','puck-uploaded-assets.generated.js');
const allowed=new Set(['.png','.jpg','.jpeg','.webp','.svg']);

fs.mkdirSync(inbox,{recursive:true});

const files=fs.readdirSync(inbox,{withFileTypes:true})
 .filter(entry=>entry.isFile()&&allowed.has(path.extname(entry.name).toLowerCase()))
 .map(entry=>entry.name)
 .sort((a,b)=>a.localeCompare(b));

const label=name=>name
 .replace(/\.[^.]+$/,'')
 .replace(/[_-]+/g,' ')
 .replace(/\s+/g,' ')
 .trim()
 .replace(/\b\w/g,c=>c.toUpperCase());

const items=files.map((name,index)=>({
 id:`puck-upload-${index+1}`,
 label:`Uploaded — ${label(name)}`,
 path:`assets/puck-inbox/${name}`,
 kind:'asset'
}));

const source=`// AUTO-GENERATED by scripts/generate-puck-assets.mjs. Do not hand-edit.\nexport const puckUploadedAssets=${JSON.stringify(items,null,2)};\n`;
fs.writeFileSync(out,source);
console.log(`Puck upload manifest: ${items.length} asset(s)`);
